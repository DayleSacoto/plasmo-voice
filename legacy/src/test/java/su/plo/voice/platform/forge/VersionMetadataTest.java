package su.plo.voice.platform.forge;

import java.io.InputStream;
import java.util.HashMap;

import cpw.mods.fml.common.MetadataCollection;
import cpw.mods.fml.common.Mod;
import cpw.mods.fml.common.ModMetadata;
import org.junit.Test;

import static org.junit.Assert.*;

/**
 * One release version, from legacyVersion in gradle.properties, reaches everything Forge shows: the @Mod version
 * and mcmod.info, which the Mods menu prints as "Version: mcmod.info (@Mod)". The voice compatibility version is a
 * separate value that only the voice handshake uses.
 */
public class VersionMetadataTest {
    /** legacyVersion as Gradle read it, passed to the tests by build.gradle.kts. */
    private static final String LEGACY_VERSION = System.getProperty("plasmovoice.legacyVersion");

    @Test
    public void releaseVersionComesFromGradleProperties() {
        assertNotNull("tests run through Gradle", LEGACY_VERSION);
        assertTrue(LEGACY_VERSION, LEGACY_VERSION.matches("\\d+\\.\\d+\\.\\d+"));
        assertEquals(LEGACY_VERSION, PlasmoVoiceMod.VERSION);
    }

    @Test
    public void voiceCompatibilityVersionIsNotTheReleaseVersion() {
        assertEquals("2.1.17", PlasmoVoiceMod.VOICE_COMPAT_VERSION);
        assertNotEquals(PlasmoVoiceMod.VOICE_COMPAT_VERSION, PlasmoVoiceMod.VERSION);
    }

    @Test
    public void modAnnotationReportsTheReleaseVersionAndAcceptsAnyRemote() {
        Mod mod = PlasmoVoiceMod.class.getAnnotation(Mod.class);
        assertEquals("plasmovoice", mod.modid());
        assertEquals(LEGACY_VERSION, mod.version());
        assertEquals("*", mod.acceptableRemoteVersions());
    }

    /** FML's own mcmod.info reader, as FMLModContainer binds it: its version is what the Mods menu lists. */
    @Test
    public void mcmodInfoReportsTheReleaseVersion() throws Exception {
        try (InputStream in = PlasmoVoiceMod.class.getResourceAsStream("/mcmod.info")) {
            assertNotNull(in);
            ModMetadata metadata = MetadataCollection.from(in, "plasmovoice")
                    .getMetadataForId(PlasmoVoiceMod.MOD_ID, new HashMap<String, Object>());
            assertFalse("mcmod.info has an entry for the mod", metadata.autogenerated);
            assertEquals("Plasmo Voice", metadata.name);
            assertEquals(LEGACY_VERSION, metadata.version);
        }
    }
}
